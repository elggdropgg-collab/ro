# Uploads assets/sounds/<Slot>/*.ogg to Roblox and writes the asset IDs into the game.
#
#   $env:ROBLOX_API_KEY = "<Open Cloud key with asset:read + asset:write>"
#   .\tools\upload-sounds.ps1 -UserId 123456        # upload as yourself
#   .\tools\upload-sounds.ps1 -GroupId 7890         # or as a group that owns the game
#
# Already uploaded files are remembered in assets/sounds/uploaded.json and skipped, so the
# script can be re-run after adding new clips. The IDs end up in
# src/shared/Config/UploadedSounds.luau, which Sounds.luau merges into the library.
param(
	[string]$ApiKey = $env:ROBLOX_API_KEY,
	[string]$UserId = $env:ROBLOX_USER_ID,
	[string]$GroupId = $env:ROBLOX_GROUP_ID,
	[string]$Dir = (Join-Path $PSScriptRoot "..\assets\sounds"),
	[string]$Out = (Join-Path $PSScriptRoot "..\src\shared\Config\UploadedSounds.luau")
)

$ErrorActionPreference = "Stop"
if (-not $ApiKey) { throw "No API key. Create one at create.roblox.com/dashboard/credentials and set `$env:ROBLOX_API_KEY." }
if (-not $UserId -and -not $GroupId) { throw "Pass -UserId (your Roblox user id) or -GroupId." }

Add-Type -AssemblyName System.Net.Http
$client = [System.Net.Http.HttpClient]::new()
$client.DefaultRequestHeaders.Add("x-api-key", $ApiKey)
$base = "https://apis.roblox.com/assets/v1"

$manifestPath = Join-Path $Dir "uploaded.json"
$manifest = @{}
if (Test-Path $manifestPath) {
	(Get-Content $manifestPath -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $manifest[$_.Name] = $_.Value }
}

function Save-Manifest {
	$ordered = [ordered]@{}
	foreach ($k in ($manifest.Keys | Sort-Object)) { $ordered[$k] = $manifest[$k] }
	$ordered | ConvertTo-Json | Set-Content -Encoding UTF8 $manifestPath
}

function Send-Audio([string]$path, [string]$displayName) {
	$creator = if ($GroupId) { @{ groupId = "$GroupId" } } else { @{ userId = "$UserId" } }
	$request = @{
		assetType = "Audio"
		displayName = $displayName
		description = "Fodder game sound"
		creationContext = @{ creator = $creator }
	} | ConvertTo-Json -Depth 5 -Compress

	$form = [System.Net.Http.MultipartFormDataContent]::new()
	$form.Add([System.Net.Http.StringContent]::new($request), "request")
	$file = [System.Net.Http.ByteArrayContent]::new([IO.File]::ReadAllBytes($path))
	$file.Headers.ContentType = [System.Net.Http.Headers.MediaTypeHeaderValue]::Parse("audio/ogg")
	$form.Add($file, "fileContent", [IO.Path]::GetFileName($path))

	$response = $client.PostAsync("$base/assets", $form).Result
	$body = $response.Content.ReadAsStringAsync().Result
	if (-not $response.IsSuccessStatusCode) { throw "upload failed ($([int]$response.StatusCode)): $body" }
	$operation = ($body | ConvertFrom-Json).path

	# Uploads are processed asynchronously; poll the operation until it has an asset id
	for ($i = 0; $i -lt 30; $i++) {
		Start-Sleep -Seconds 2
		$poll = $client.GetAsync("$base/$operation").Result.Content.ReadAsStringAsync().Result | ConvertFrom-Json
		if ($poll.done) {
			if ($poll.error) { throw "processing failed: $($poll.error | ConvertTo-Json -Compress)" }
			return $poll.response.assetId
		}
	}
	throw "timed out waiting for $operation"
}

$root = (Resolve-Path $Dir).Path
$files = Get-ChildItem $root -Recurse -Filter *.ogg | Sort-Object FullName
$failed = 0
foreach ($f in $files) {
	$key = $f.FullName.Substring($root.Length + 1).Replace("\", "/")
	if ($manifest.ContainsKey($key)) { continue }
	$slot = $f.Directory.Name
	try {
		$id = Send-Audio $f.FullName "Fodder $slot $($f.BaseName)"
		$manifest[$key] = "$id"
		Save-Manifest
		"uploaded  $key  ->  $id"
	} catch {
		$failed++
		Write-Warning "$key : $_"
	}
	Start-Sleep -Milliseconds 800
}

# Regenerate the Luau module from everything uploaded so far
$bySlot = [ordered]@{}
foreach ($k in ($manifest.Keys | Sort-Object)) {
	$slot = $k.Split("/")[0]
	if (-not $bySlot.Contains($slot)) { $bySlot[$slot] = New-Object System.Collections.Generic.List[string] }
	$bySlot[$slot].Add($manifest[$k])
}
$lines = @(
	"--!strict",
	"-- Generated by tools/upload-sounds.ps1 from assets/sounds. Do not edit by hand.",
	"",
	"local Uploaded: { [string]: { string } } = {"
)
foreach ($slot in $bySlot.Keys) {
	$ids = ($bySlot[$slot] | ForEach-Object { "`"rbxassetid://$_`"" }) -join ", "
	$lines += "`t$slot = { $ids },"
}
$lines += "}", "", "return Uploaded"
[IO.File]::WriteAllText((Resolve-Path (Split-Path $Out)).Path + "\" + (Split-Path $Out -Leaf), ($lines -join "`n") + "`n")

"Done: $($manifest.Count) uploaded, $failed failed. Wrote $Out"
if ($failed -gt 0) { exit 1 }
